function buildCrescentPathString(): string {
  const pieces = runBooleanOperation(
    [
      { id: 'c-base', name: 'Base', kind: 'circle', x: 0, y: 0, w: 280, h: 280, rotation: 0, colour: '#fbbf24' },
      { id: 'c-cut', name: 'Cut', kind: 'circle', x: 88, y: -22, w: 250, h: 250, rotation: 0, colour: '#0f172a' },
    ],
    'subtract',
  );
  if (pieces[0]) {
    return multiPolygonToNormalisedPath(pieces[0].multiPolygon).path;
  }
  return 'M 50 5 A 45 45 0 1 0 95 65 A 36 36 0 1 1 50 5 Z';
}

