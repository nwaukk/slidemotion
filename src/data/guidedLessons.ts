function makeGuidedText(
  id: string,
  name: string,
  x: number,
  y: number,
  w: number,
  h: number,
  text: string,
  fontSize: number,
  fontWeight: 400 | 500 | 600 | 700 | 800,
  colour: string,
  align: 'left' | 'centre' | 'right',
): SlideElement {
  return {
    id,
    name,
    type: 'text',
    x,
    y,
    w,
    h,
    rotation: 0,
    locked: false,
    visible: true,
    text,
    style: createDefaultStyle({
      fill: {
        mode: 'none',
        colour: '#000000',
        gradientStart: '#000000',
        gradientEnd: '#000000',
        gradientAngle: 0,
        gradientType: 'linear',
      },
      typography: {
        fontFamily: 'Plus Jakarta Sans',
        fontSize,
        fontWeight,
        italic: false,
        underline: false,
        colour,
        align,
        verticalAlign: 'middle',
        lineHeight: 1.2,
        letterSpacing: -0.5,
      },
    }),
    animations: [],
  };
}

function makeGuidedShape(
  id: string,
  name: string,
  shapeKind: SlideElement['shapeKind'],
  x: number,
  y: number,
  w: number,
  h: number,
  colour: string,
  text: string,
  textColour = '#f8fafc',
  fontSize = 32,
): SlideElement {
  return {
    id,
    name,
    type: 'shape',
    shapeKind,
    x,
    y,
    w,
    h,
    rotation: 0,
    locked: false,
    visible: true,
    text,
    style: createDefaultStyle({
      fill: {
        mode: 'solid',
        colour,
        gradientStart: colour,
        gradientEnd: colour,
        gradientAngle: 135,
        gradientType: 'linear',
      },
      cornerRadius: shapeKind === 'rounded-rectangle' ? 24 : 0,
      typography: {
        fontFamily: 'Plus Jakarta Sans',
        fontSize,
        fontWeight: 700,
        italic: false,
        underline: false,
        colour: textColour,
        align: 'centre',
        verticalAlign: 'middle',
        lineHeight: 1.25,
        letterSpacing: 0,
      },
    }),
    animations: [],
  };
}

function makeGuidedAnim(
  id: string,
  effect: string,
  start: ElementAnimation['start'],
  duration: number,
  delay: number,
  order: number,
  options: Record<string, string | number | boolean> = {},
): ElementAnimation {
  return {
    id,
    category: 'entrance',
    effect,
    options,
    start,
    duration,
    delay,
    repeat: 1,
    rewind: false,
    order,
  };
}

function makeGuidedStep(cfg: {
  id: string;
  stepNumber: number;
  title: string;
  instruction: string;
  designTip: string;
  requireTextMatch?: boolean;
  targetElement: SlideElement;
  finale: ElementAnimation;
}): GuidedLessonStep {
  return {
    id: cfg.id,
    stepNumber: cfg.stepNumber,
    title: cfg.title,
    instruction: cfg.instruction,
    designTip: cfg.designTip,
    requireTextMatch: Boolean(cfg.requireTextMatch),
    targetElement: cfg.targetElement,
    finaleAnimations: [cfg.finale],
  };
}

